export class I18n {
  private locale: SupportedLocale = 'en';

  setLocale(rawLocale: string | null | undefined): void {
    if (!rawLocale) {
      this.locale = 'en';
      return;
    }
    const short = rawLocale.toLowerCase().slice(0, 2) as SupportedLocale;
    this.locale = short in TRANSLATIONS ? short : 'en';
  }

  getLocale(): SupportedLocale {
    return this.locale;
  }

  t(key: TranslationKey): string {
    return TRANSLATIONS[this.locale]?.[key] ?? EN_STRINGS[key];
  }
}

